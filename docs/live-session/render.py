"""Render claude -p stream-json sessions to Markdown: every tool call with its arguments, the start of each
result, and the final answer, unedited. usage: render.py out.md title:file.jsonl[,file2.jsonl] ..."""
import json, os, sys

MAX_RESULT_LINES = 12


def text_of(content):
    if not isinstance(content, str):
        content = "".join(c.get("text", "") for c in content if isinstance(c, dict))
    try:  # MCP results arrive as {"result": "..."}
        return json.loads(content)["result"]
    except (ValueError, KeyError, TypeError):
        return content


def short(text):
    lines = text.strip().splitlines()
    head = lines[:MAX_RESULT_LINES]
    # keep the evidence handle line even when the result is cut
    ev = [l for l in lines[MAX_RESULT_LINES:] if l.startswith("Evidence [Q")]
    out = head + (["…"] + ev[:1] if len(lines) > MAX_RESULT_LINES else [])
    if len(lines) > MAX_RESULT_LINES:
        out.append(f"(result shortened here: {len(lines)} lines in full in the raw session)")
    return "\n".join(l[:300] for l in out)


def render(title, files):
    md, n, cost, turns, ms = [f"## {title}", ""], 0, 0.0, 0, 0
    for path in files:
        pending = {}
        prompt = path.rsplit(".", 1)[0] + ".prompt.txt"  # the -p text, which stream-json does not repeat
        if os.path.exists(prompt):
            md += ["**User" + (" (same session, `--resume`)" if path != files[0] else "") + ":**", "",
                   "> " + open(prompt).read().strip().replace("\n", "\n> "), ""]
        for line in open(path):
            ev = json.loads(line)
            t = ev.get("type")
            if t == "user" and isinstance(ev.get("message", {}).get("content"), str):
                md += ["**User:**", "", "> " + ev["message"]["content"].replace("\n", "\n> "), ""]
            if t == "assistant":
                for c in ev["message"]["content"]:
                    if c.get("type") == "tool_use" and c["name"] == "ToolSearch":
                        pending[c["id"]] = None  # Claude Code loading the tool schemas, not a server call
                    elif c.get("type") == "tool_use":
                        n += 1
                        name = c["name"].replace("mcp__serenedb-extractor__", "")
                        pending[c["id"]] = n
                        md += [f"**Call {n}: `{name}`**", "", "```json", json.dumps(c["input"], ensure_ascii=False), "```", ""]
            if t == "user":
                for c in ev["message"]["content"] if isinstance(ev["message"]["content"], list) else []:
                    if c.get("type") == "tool_result" and pending.get(c["tool_use_id"], 0) is not None:
                        md += [f"Result of call {pending.get(c['tool_use_id'], '?')}:", "", "```text", short(text_of(c.get("content", ""))), "```", ""]
            if t == "result":
                cost += ev.get("total_cost_usd") or 0
                turns += ev.get("num_turns") or 0
                ms += ev.get("duration_ms") or 0
                md += ["**Final answer:**", "", ev.get("result", "").strip(), ""]
    md.insert(2, f"*{n} tool calls, {turns} turns, {ms/1000:.0f} s, ${cost:.2f}.*\n")
    return md


out = ["<!-- generated by docs/live-session/render.py from the raw sessions in docs/live-session/ -->"]
for arg in sys.argv[2:]:
    title, files = arg.split(":", 1)
    out += render(title, files.split(","))
open(sys.argv[1], "w").write("\n".join(out) + "\n")
