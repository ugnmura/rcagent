"""Replay the worked investigation (docs/worked-investigation.md): the tool calls an agent makes for the
engineer, the team lead and the manager, through the MCP server itself, and write every result together
with the full queries behind it to docs/worked-investigation-transcript.md.

    SERENEDB_READER_URL=... uv run python scripts/worked_investigation.py

Needs the base corpus loaded (scripts/load_base_corpus.py). Template IDs depend on the catalog's history,
so steps find them by their text in the survey results.
"""

import asyncio
import json
import os
import re
import time
from pathlib import Path
from typing import Any

from mcp.shared.memory import create_connected_server_and_client_session

from serenedb_extractor.config import Settings
from serenedb_extractor.context import AppContext
from serenedb_extractor.server import build_server

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "worked-investigation-transcript.md"
NODE = "R30-M0-N9-C:J16-U01"
SEVERE = ["FATAL", "ERROR", "SEVERE", "FAILURE", "CRITICAL"]


def template_id(survey_out: str, text: str) -> str:
    """The T<n> of the first template line containing `text`."""
    for line in survey_out.splitlines():
        m = re.match(r"^(T\d+)  (.*)$", line)
        if m and text in m.group(2):
            return m.group(1)
    raise SystemExit(f"no template containing {text!r} in the survey result")


def occurrence(out: str) -> str:
    m = re.search(r"\s(\S+#\d+|e:\d+)\s", out)
    if not m:
        raise SystemExit("no occurrence ID in the result")
    return m.group(1)


class Session:
    def __init__(self, client: Any) -> None:
        self.client = client
        self.parts: list[str] = []
        self.step = 0

    async def call(self, tool: str, **args: Any) -> str:
        began = time.perf_counter()
        result = await self.client.call_tool(tool, args)
        took = time.perf_counter() - began
        out = "\n".join(getattr(b, "text", "") for b in result.content)
        handle = re.search(r"Evidence \[(Q\d+)\]", out)
        full = ""
        if handle:
            ev = await self.client.call_tool("show_evidence", {"ids": [handle.group(1)], "include_result": False})
            full = "\n".join(getattr(b, "text", "") for b in ev.content)
        self.step += 1
        self.parts += [
            f"#### Step {self.step}: `{tool}` ({took:.2f} s wall clock)",
            "```json",
            json.dumps(args, indent=None),
            "```",
            "Result:",
            "```text",
            re.split(r"\nEvidence \[Q\d+\]", out)[0].replace("\nNote: only a reader URL", "\n(Note: only a reader URL"),
            "```",
        ]
        if full:
            self.parts += ["Queries that ran (from show_evidence):", "```sql", full, "```"]
        return out

    def heading(self, text: str) -> None:
        self.parts += ["", text, ""]


async def run() -> None:
    settings = Settings.from_env(os.environ)
    mcp = build_server(lambda: AppContext.from_settings(settings))
    async with create_connected_server_and_client_session(mcp._mcp_server) as client:
        s = Session(client)
        s.heading("# Worked investigation: transcript")
        s.parts.append(
            "Generated by `scripts/worked_investigation.py` against the base corpus (Loghub BGL and OpenStack, "
            "loaded with `scripts/load_base_corpus.py`). Every result below is the tool's output as the agent saw "
            "it, followed by the queries that produced it. Times are UTC."
        )

        s.heading("## Engineer: what failed on BGL, where, and what happened just before?")
        await s.call("describe_logs", log_table="bgl")
        await s.call("count_logs", log_tables=["bgl"], filters={"level": "FATAL"}, group_by=["host"], limit=5)
        first = await s.call(
            "search_logs", log_table="bgl", text="data TLB error interrupt", filters={"host": NODE},
            order="oldest", limit=3,
        )
        await s.call(
            "count_logs", log_tables=["bgl"], text="data TLB error interrupt", filters={"host": NODE},
            group_by=["time:1h"],
        )
        await s.call("get_context", log_table="bgl", occurrence=occurrence(first), window_minutes=60, before=12, after=4)
        await s.call(
            "get_context", log_table="bgl", occurrence=occurrence(first), scope="everything", window_minutes=10,
            before=10, after=2,
        )
        await s.call("search_logs", log_table="bgl", text="L2 DCU", limit=5)
        await s.call(
            "count_logs", log_tables=["bgl"], filters={"host": NODE, "level": SEVERE}, group_by=["level", "time:1d"]
        )

        s.heading("## Team lead: which problems recur, how often, and which teams are involved?")
        await s.call("count_logs", group_by=["team", "level"])
        await s.call("count_logs", log_tables=["bgl"], filters={"level": "FATAL"}, group_by=["time:7d"], limit=40)
        week = await s.call(
            "survey", log_table="bgl", start="2005-06-09", end="2005-06-16", filters={"level": "FATAL"}, limit=6
        )
        ids = [template_id(week, t) for t in ("data TLB error interrupt", "data storage interrupt", "instruction address")]
        await s.call(
            "locate_occurrences", log_table="bgl", templates=ids, start="2005-06-09", end="2005-06-16",
            group_by=["host"], limit=3, examples_per_group=1,
        )
        await s.call(
            "count_logs", log_tables=["bgl"], start="2005-06-14", end="2005-06-15", filters={"level": "FATAL"},
            group_by=["time:1h"],
        )
        os_warn = await s.call(
            "survey", log_table="openstack", filters={"level": ["WARNING", "ERROR", "CRITICAL"]}, limit=6
        )
        await s.call("count_logs", log_tables=["openstack"], group_by=["time:1h"], limit=40)
        await s.call(
            "trend", log_table="openstack", start="2017-05-16T15:00:00", end="2017-05-17T06:00:00", bucket="hour",
            templates=[template_id(os_warn, "Unknown base file")], exact=True,
        )
        await s.call(
            "count_logs", log_tables=["openstack"], filters={"service": "nova-api"}, group_by=["status", "http_method"],
            limit=10,
        )
        await s.call(
            "run_sql",
            sql=(
                "SELECT service, count(*) AS requests, round(quantile_cont(latency_s, 0.5), 3) AS p50_s, "
                "round(quantile_cont(latency_s, 0.95), 3) AS p95_s, round(max(latency_s), 3) AS max_s, "
                "count(*) FILTER (WHERE status >= 400) AS http_4xx_5xx FROM extractor.lt_openstack "
                "WHERE latency_s IS NOT NULL GROUP BY 1"
            ),
        )

        s.heading("## Manager: which observed problems deserve attention first?")
        await s.call("count_logs", filters={"level": SEVERE}, group_by=["team"])
        dec = await s.call(
            "survey", log_table="bgl", start="2005-11-01", end="2006-01-01", filters={"level": "FATAL"}, limit=5
        )
        dec_ids = re.findall(r"^(T\d+)  \S", dec, re.M)[:4]  # template lines (two spaces), not merge notes
        await s.call(
            "trend", log_table="bgl", start="2005-12-01", end="2006-01-01", templates=dec_ids, bucket="day", exact=True
        )
        await s.call("count_logs", log_tables=["bgl"], start="2005-12-01", end="2006-01-01",
                     filters={"level": "FATAL"}, group_by=["team", "component"])
        await s.call("rank_problems", log_tables=["bgl"], start="2005-12-01", end="2006-01-01", limit=6)

        s.heading("## Check against the dataset's own labels")
        await s.call("count_logs", log_tables=["bgl"], text="data TLB error interrupt", group_by=["level"])
        await s.call("count_logs", log_tables=["bgl"], filters={"alert_label": "KERNDTLB"})

    OUT.write_text("\n".join(s.parts) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    asyncio.run(run())
