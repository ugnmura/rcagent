"""Replay the short worked investigation in the README ("Two 503s at 06:25"): the tool calls an engineer
makes on OpenStack, through the MCP server itself, and write every result with the queries behind it to
docs/keystone-503-transcript.md.

    SERENEDB_READER_URL=... SERENEDB_ALLOW_SQL=1 uv run python scripts/worked_investigation_keystone.py

Needs the base corpus loaded (scripts/load_base_corpus.py).
"""

import asyncio
import os
from pathlib import Path

from mcp.shared.memory import create_connected_server_and_client_session
from worked_investigation import Session

from serenedb_extractor.config import Settings
from serenedb_extractor.context import AppContext
from serenedb_extractor.server import build_server

OUT = Path(__file__).resolve().parents[1] / "docs" / "keystone-503-transcript.md"


async def run() -> None:
    settings = Settings.from_env(os.environ)
    mcp = build_server(lambda: AppContext.from_settings(settings))
    async with create_connected_server_and_client_session(mcp._mcp_server) as client:
        s = Session(client)
        s.heading("# Worked investigation: two 503s at 06:25 (transcript)")
        s.parts.append(
            "Generated by `scripts/worked_investigation_keystone.py` against the base corpus (Loghub OpenStack, "
            "loaded with `scripts/load_base_corpus.py`). Every result below is the tool's output as the agent saw "
            "it, followed by the queries that produced it. Times are UTC."
        )
        s.heading("## What are the most severe entries in OpenStack?")
        await s.call(
            "count_logs", log_tables=["openstack"], filters={"level": ["WARNING", "ERROR", "CRITICAL"]},
            group_by=["level", "component"], limit=10,
        )
        await s.call(
            "search_logs", log_table="openstack", filters={"component": "keystonemiddleware.auth_token"},
            order="oldest", limit=6,
        )
        await s.call(
            "count_logs", log_tables=["openstack"], filters={"status": 503}, group_by=["http_method", "http_path"],
            limit=5,
        )
        s.heading("## What happened around the first one?")
        await s.call(
            "get_context", log_table="openstack", occurrence="/logs/loghub/parquet/openstack.parquet#52285",
            scope="everything", window_minutes=2, before=6, after=6,
        )
        s.heading("## When did each service go quiet?")
        await s.call(
            "run_sql",
            sql=(
                "SELECT service, ts AS last_before_gap, nxt AS next_entry, "
                "round((epoch(nxt) - epoch(ts)) / 60, 1) AS gap_min FROM (SELECT service, ts, "
                "lead(ts) OVER (PARTITION BY service ORDER BY ts, entry_id) AS nxt FROM extractor.lt_openstack "
                "WHERE source_file <> 'openstack_abnormal.log') WHERE epoch(nxt) - epoch(ts) > 300 "
                "ORDER BY ts LIMIT 5"
            ),
        )
        await s.call(
            "run_sql",
            sql=(
                "SELECT source_file, min(ts) AS first, max(ts) AS last, count(*) AS entries "
                "FROM extractor.lt_openstack GROUP BY 1 ORDER BY 2"
            ),
        )
        s.heading("## Day 2: did the traffic come back?")
        await s.call(
            "count_logs", log_tables=["openstack"], text="/servers/detail", start="2017-05-17T00:00:00",
            end="2017-05-17T13:00:00", group_by=["time:1h"], limit=20,
        )
        await s.call(
            "count_logs", log_tables=["openstack"], text="seconds to spawn the instance",
            start="2017-05-17T00:00:00", end="2017-05-17T13:00:00", group_by=["time:1h"], limit=20,
        )

    OUT.write_text("\n".join(s.parts) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    asyncio.run(run())
